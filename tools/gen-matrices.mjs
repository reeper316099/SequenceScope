// Turns the raw NCBI matrix files in data/matrices/ into src/bio/matrices.data.ts (never hand-typed values).
// Run: node tools/gen-matrices.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const names = ['BLOSUM45', 'BLOSUM62', 'BLOSUM80'];
let out = '// GENERATED by tools/gen-matrices.mjs from data/matrices/* — do not edit by hand.\n';
out += "import type { RawMatrix } from './matrices';\n\nexport const RAW_MATRICES: readonly RawMatrix[] = [\n";
for (const name of names) {
  const text = readFileSync(`data/matrices/${name}`, 'utf8');
  const lines = text.split(/\r?\n/).filter((l) => l.trim() !== '' && !l.startsWith('#'));
  const letters = lines[0].trim().split(/\s+/);
  const n = letters.length;
  const flat = [];
  for (let r = 0; r < n; r++) {
    const parts = lines[r + 1].trim().split(/\s+/);
    if (parts[0] !== letters[r]) throw new Error(`row label mismatch in ${name}`);
    for (let c = 0; c < n; c++) flat.push(Number(parts[c + 1]));
  }
  // Safety checks: square, symmetric, integer.
  for (let r = 0; r < n; r++) for (let c = 0; c < n; c++) {
    if (flat[r * n + c] !== flat[c * n + r]) throw new Error(`${name} not symmetric at ${letters[r]}${letters[c]}`);
    if (!Number.isInteger(flat[r * n + c])) throw new Error(`${name} non-integer`);
  }
  const sha = createHash('sha256').update(readFileSync(`data/matrices/${name}`)).digest('hex');
  out += `  { name: '${name}', letters: '${letters.join('')}', values: [${flat.join(',')}], sha256: '${sha}' },\n`;
}
out += '];\n';
writeFileSync('src/bio/matrices.data.ts', out);
console.log('wrote src/bio/matrices.data.ts');
