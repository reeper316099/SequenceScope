"""Generates DATA-SOURCES.md and examples/NOTICE from examples/*/metadata.json and data/matrices (so the text cannot drift from the data).
Run: python3 -I tools/gen_data_sources.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    """Write the two documents."""
    sets = [json.loads(p.read_text()) for p in sorted((ROOT / "examples").glob("*/metadata.json"))]
    sums = {l.split()[1]: l.split()[0] for l in (ROOT / "data/matrices/SHA256SUMS").read_text().splitlines() if l.strip()}
    out = ["# DATA-SOURCES.md\n",
           "Every bundled sequence set was downloaded from its real source by accession with `tools/fetch_examples.py` (nothing was typed or recalled from memory), "
           "checksummed, and described in a `metadata.json` next to the FASTA. This file is generated by `tools/gen_data_sources.py` from those files.\n",
           "The app itself makes **no network requests**; the downloads happen only when a developer runs the script.\n",
           "## Sequence sets\n"]
    for m in sets:
        r0 = m["records"][0]
        out.append(f"### {m['title']}  (`examples/{m['id']}/`)\n")
        out.append(f"- **Purpose:** {m['purpose']}\n- **Molecule:** {m['molecule']}\n- **Source database:** {r0['database']}"
                   + (f" (UniProt release {r0['release']})" if 'release' in r0 else "") + f"\n- **Retrieved:** {m['retrieved']}\n")
        out.append(f"- **License / terms:** {m['license']['name']}. Quoted from {m['license']['source_url']} (checked {m['license']['license_checked']}): “{m['license']['quote']}”")
        if m["license"].get("caveat"):
            out.append(f"  - Caveat: {m['license']['caveat']}")
        out.append(f"- **Citation:** {m['citation']}\n- **Redistribution verdict:** allowed in a public repository and in installers, with attribution (see `examples/NOTICE`).\n- **FASTA SHA-256:** `{m['fasta_sha256']}`\n- **Notes:** {m['notes']}")
        if "aligned" in m:
            a = m["aligned"]
            out.append(f"- **Derived alignment:** `aligned.fasta` produced by {a['tool']} {a['version']} (`{a['command']}`; {a['tool_license']}). {a['note']} SHA-256 `{a['sha256']}`")
        out.append("\n| Accession | Record header | Length |\n|---|---|---|")
        for r in m["records"]:
            header = r["header"][:90].replace("|", "\\|")
            out.append(f"| {r['accession']} | {header} | {r['length']} |")
        out.append("")
    out += ["## Substitution matrices\n",
            "BLOSUM45, BLOSUM62 and BLOSUM80 come from the NCBI BLAST matrices directory (https://ftp.ncbi.nlm.nih.gov/blast/matrices/; file header: “Matrix made by matblas from blosum62.iij”), downloaded 2026-11-08 into `data/matrices/`; `src/bio/matrices.data.ts` is generated from them by `tools/gen-matrices.mjs` (never typed by hand).\n",
            "| File | SHA-256 |\n|---|---|"]
    out += [f"| {k} | `{v}` |" for k, v in sorted(sums.items())]
    out += ["",
            "- **Independent check:** the three files are byte-identical to the copies bundled with Biopython 1.86, and BLOSUM62 is cell-for-cell identical to an EMBOSS copy (576 cells); all are symmetric. This is a consistency check, not a truly independent derivation: all copies descend from the same NCBI/matblas files. The original Henikoff files (blocks.fhcrc.org) were not reachable.",
            "- **Citation:** Henikoff S, Henikoff JG (1992). Amino acid substitution matrices from protein blocks. Proc Natl Acad Sci USA 89(22):10915-10919. doi:10.1073/pnas.89.22.10915 (verified against Crossref).",
            "- **License status: NOT formally confirmed.** The files carry no license text. They are small numeric tables distributed publicly by NCBI inside its BLAST software and bundled by Biopython and EMBOSS. I could not find an explicit redistribution grant; if you need certainty (for example before wider distribution), ask NCBI or generate the numbers from the published paper. This is not legal advice.\n",
            "## Other bundled or derived material\n",
            "- **Worked examples** (`tests/fixtures/worked-examples/`): short facts from Rosalind (problems GLOB and GAFF, rosalind.info) and Wikipedia (Needleman–Wunsch, Smith–Waterman, UPGMA and Neighbor joining articles; text is CC BY-SA), used only as test data with the source URL and access date (2026-11-08) recorded next to each. Not shipped in the installers.",
            "- **Reference fixtures** (`tests/fixtures/reference/`): outputs of Biopython 1.86 and SciPy 1.11.1 on random cases generated by `tools/`; they record versions, parameters and seeds. Not shipped in the installers.",
            "- **MAFFT 7.526** (BSD-3-Clause) was used once to make the two `aligned.fasta` files; it is not part of the app.",
            "- **Runtime libraries bundled into the app** (all permissive): Electron (MIT; Chromium and Node licenses are in the installer's `LICENSES.chromium.html`), zod (MIT), Chart.js (MIT).\n"]
    (ROOT / "DATA-SOURCES.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    notice = ["NOTICE: attributions for the example data bundled with SequenceScope\n",
              "UniProt-derived sequences (examples: globin_alpha_vertebrates, globin_alpha_primates_near_identical, pair_globin_alpha_beta_gaps, pair_unrelated):",
              "  Source: UniProtKB/Swiss-Prot (https://www.uniprot.org), release 2026_04, retrieved 2026-11-08.",
              "  © The UniProt Consortium. Licensed under Creative Commons Attribution 4.0 International (CC BY 4.0): https://creativecommons.org/licenses/by/4.0/",
              "  Changes: records were re-wrapped to 60 columns, and subsets were selected. Sequences are unchanged.",
              "  UniProt statement: \"All databases and documents in the UniProt FTP directory may be copied and redistributed freely, without advance permission, provided that this copyright statement is reproduced with each copy.\"",
              "  Citation: " + sets[0]["citation"] if sets and sets[0]["records"][0]["database"] == "UniProtKB" else "",
              "",
              "NCBI-derived sequences (example: mito_cytb_mammals):",
              "  Source: NCBI Nucleotide, RefSeq mitochondrial genomes; the CYTB coding sequence of each record was extracted using the record's own gene annotation. Retrieved 2026-11-08.",
              "  NCBI policy (https://www.ncbi.nlm.nih.gov/home/about/policies/): \"NCBI itself places no restrictions on the use or distribution of the data contained therein.\" Some submitters may claim rights in portions of the data.",
              "",
              "Derived alignments (aligned.fasta in globin_alpha_vertebrates and mito_cytb_mammals) were produced with MAFFT 7.526 (BSD-3-Clause) from the records above.",
              "",
              "Each example folder's metadata.json lists accessions, retrieval date, license sentence, citation and a SHA-256 checksum."]
    (ROOT / "examples" / "NOTICE").write_text("\n".join(x for x in notice) + "\n", encoding="utf-8")
    print("wrote DATA-SOURCES.md and examples/NOTICE")


if __name__ == "__main__":
    main()
